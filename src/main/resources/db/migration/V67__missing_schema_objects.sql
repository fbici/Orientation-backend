CREATE TABLE bo_notifications (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(), version BIGINT NOT NULL DEFAULT 0,
 type VARCHAR(100) NOT NULL,title VARCHAR(500) NOT NULL,message TEXT,user_id VARCHAR(100),
 read BOOLEAN NOT NULL DEFAULT FALSE,link VARCHAR(500),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 created_by VARCHAR(100),updated_by VARCHAR(100),deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_bo_notification_user ON bo_notifications(user_id,created_at) WHERE NOT deleted;
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, action VARCHAR(255) NOT NULL,
 entity_type VARCHAR(255) NOT NULL,entity_id VARCHAR(255),user_id VARCHAR(255),username VARCHAR(255),
 ip_address VARCHAR(255),user_agent VARCHAR(255),details TEXT,old_values TEXT,new_values TEXT,
 created_at TIMESTAMP
);
CREATE INDEX idx_audit_created ON audit_events(created_at);
