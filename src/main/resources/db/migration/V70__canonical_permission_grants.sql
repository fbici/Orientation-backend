SELECT gen_random_uuid(),0,rp.role_id,target.id,NOW(),NOW(),FALSE FROM aliases a
 JOIN permissions old ON old.code=a.old_code
 JOIN role_permissions rp ON rp.permission_id=old.id
 JOIN permissions target ON target.code=a.new_code
 WHERE NOT old.deleted AND NOT rp.deleted
 ON CONFLICT(role_id,permission_id) DO NOTHING;
